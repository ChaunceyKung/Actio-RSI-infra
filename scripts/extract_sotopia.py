"""Reproduce licensed definitions from a read-only pinned checkout, without importing it."""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[1]
PIN='a0aaafb440e570e5e61b7c44a44e5e417c545383'


def extract(source, check=False):
    assert subprocess.check_output(['git','rev-parse','HEAD'],cwd=source,text=True).strip()==PIN
    assert not subprocess.check_output(['git','status','--porcelain'],cwd=source,text=True).strip()
    entries=[]
    def definitions(path,names):
        raw=(source/path).read_bytes(); text=raw.decode(); lines=text.splitlines(keepends=True)
        tree=ast.parse(text); pieces=[]
        for name in names:
            node=next(n for n in tree.body if getattr(n,'name',None)==name)
            start=min([node.lineno]+[d.lineno for d in getattr(node,'decorator_list',[])])
            part=''.join(lines[start-1:node.end_lineno]).replace('\r\n','\n').rstrip()+'\n'
            entries.append({'source':path,'symbol':name,'start':start,'end':node.end_lineno,
                            'source_sha256':hashlib.sha256(raw).hexdigest(),
                            'definition_lf_sha256':hashlib.sha256(part.encode()).hexdigest()})
            pieces.append(part)
        return '\n\n'.join(pieces)
    product='''# MIT SOTOPIA original definitions; generated by scripts/extract_sotopia.py.
# Only import glue differs: storage Field -> pydantic.Field; no storage/network imports.
import json
import re
from typing import Any, Generic, Type, TypeVar
from pydantic import BaseModel, ConfigDict, Field, field_validator
import json_repair
OutputType = TypeVar("OutputType", bound=object)
T = TypeVar("T", bound=BaseModel)
T_eval_dim = TypeVar("T_eval_dim", bound=BaseModel)

'''
    for path,names in [
        ('sotopia/database/base_models.py',['LLMBaseModel','LLMEvalBaseModel']),
        ('sotopia/database/evaluation_dimensions.py',['zero_to_ten','minus_five_to_five','PositiveReasoningScore','BidirectionalReasoningScore']),
        ('sotopia/generation_utils/output_parsers.py',['OutputParser','PydanticOutputParser']),
        ('sotopia/envs/evaluators.py',['EvaluationForAgents']),
    ]: product+=definitions(path,names)+'\n\n'
    fixture='''# Test-only original SOTOPIA evaluator definitions. MIT. Never a product evaluator.
import abc
import logging
from typing import Any, Generic, TypeVar
import gin
from pydantic import BaseModel, validate_call
from actio._vendor.sotopia import LLMEvalBaseModel, EvaluationForAgents, PydanticOutputParser
T_eval_dim = TypeVar("T_eval_dim", bound=BaseModel)
log = logging.getLogger("evaluators")
# Test-side message seam replaces the simulator message dependency.
class Message(BaseModel):
    text: str
    def to_natural_language(self): return self.text
def supports_response_schema(**kwargs):
    raise AssertionError("transport seam must be injected by characterization")
async def agenerate(**kwargs):
    raise AssertionError("generation seam must be injected by characterization")

'''+definitions('sotopia/envs/evaluators.py',['Evaluator','EpisodeLLMEvaluator'])
    metadata={'upstream':'https://github.com/sotopia-lab/sotopia','commit':PIN,'metadata_version':'0.1.5',
              'license':'MIT','definitions':entries,
              'modifications':['original definition text normalized to LF only','imports limited to parser/schema closure',
                               'storage Field replaced by pydantic.Field (no index/storage fields selected)',
                               'test evaluator uses controlled Message/generation/transport seams'],
              'generated_sha256':hashlib.sha256(product.encode()).hexdigest(),
              'test_evaluator_sha256':hashlib.sha256(fixture.encode()).hexdigest()}
    outputs={'src/actio/_vendor/__init__.py':'', 'src/actio/_vendor/sotopia.py':product,
             'src/actio/_vendor/SOTOPIA_LICENSE':(source/'LICENSE').read_text(encoding='utf8'),
             'src/actio/_vendor/sotopia_provenance.json':json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',
             'tests/fixtures/sotopia_episode.py':fixture}
    for name,text in outputs.items():
        path=ROOT/name
        if check: assert path.read_bytes()==text.encode(), 'extraction differs: '+name
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(text.encode())
    print(json.dumps({'pin':PIN,'definitions':len(entries),'check':check,'status':'PASS'}))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('--check',action='store_true')
    a=p.parse_args();extract(a.source,a.check)
